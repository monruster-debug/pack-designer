import assert from 'node:assert/strict';
import {verifyImportedImages} from '../imported-images.js';
const specs=[{id:'start',width:520,height:680},{id:'game',width:608,height:262},{id:'collapsed',width:1556,height:67}];
const rec=url=>({assetId:url,sourceUrl:url,bytes:1234,mime:'image/webp'});
const old={game:rec('strip'),collapsed:rec('wide'),start:rec('vertical')};
const size=url=>({strip:{width:1556,height:67},wide:{width:608,height:262},vertical:{width:520,height:680}}[url]);
const next=await verifyImportedImages(old,specs,async url=>size(url));
assert.equal(next.game.sourceUrl,'wide');assert.equal(next.collapsed.sourceUrl,'strip');
assert.ok(Object.values(next).every(r=>r.sourceVerified&&!r.verificationError));
assert.equal(old.game.sourceUrl,'strip','Input remains unchanged until caller saves the transaction');
const invalid=await verifyImportedImages({game:rec('bad')},specs,async()=>({width:1,height:1}));
assert.match(invalid.game.verificationError,/1 × 1/);
const large=await verifyImportedImages({start:{...rec('vertical'),bytes:1048577}},specs,async url=>size(url));
assert.match(large.start.verificationError,/1 МБ/);
const failed=await verifyImportedImages({start:rec('vertical')},specs,async()=>{throw Error('network');});
assert.match(failed.start.verificationError,/Не удалось загрузить/);
const changed={start:rec('vertical')},local={assetId:'user-upload'};
const raced=await verifyImportedImages(changed,specs,async url=>{changed.start=local;return size(url);});
assert.equal(raced.start,local,'In-flight verification never overwrites a local upload');
console.log('Imported images: decoded dimensions, swapped slots, invalid size, 1 MB limit, network failure and upload race passed.');
