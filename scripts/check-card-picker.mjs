import assert from 'node:assert/strict';
import {availableLibraryCards,addLibraryCards,addSelectedLibraryCards} from '../card-picker-model.js';
import fs from 'node:fs';
import vm from 'node:vm';
const card={id:'a',name:'Медицинский кабинет',description:'Помощь',relation:true,players_count:2,image:'image'};
const packs=[{id:'p1',cards:{bunker:[card],health:[{id:'h',name:'Здоров'}]}},{id:'p2',cards:{bunker:[card,{id:'b',name:'Кухня'}]}}];
const orphan={id:'o',type:'bunker',name:'Склад',packIds:[]};
assert.equal(availableLibraryCards(packs,[orphan],'bunker').length,3);
assert.equal(availableLibraryCards(packs,[],'bunker',{query:'МЕДИЦ'}).length,1);
assert.equal(availableLibraryCards(packs,[],'bunker',{packId:'p1'}).length,1);
assert.equal(availableLibraryCards(packs,[],'bunker',{query:'xxx'}).length,0);
for(const type of ['special','disaster'])assert.deepEqual(availableLibraryCards(packs,[orphan],type),[]);
const target={cards:{bunker:[]}},all=availableLibraryCards(packs,[orphan],'bunker');
assert.equal(addLibraryCards(target,'bunker',all,new Set(['a','o','h'])),2);
assert.equal(addLibraryCards(target,'bunker',all,new Set(['a','o'])),0);
assert.equal(target.cards.bunker[0].players_count,2);
assert.ok(!('packIds' in target.cards.bunker[0]));
target.cards.bunker[0].name='Changed';assert.equal(card.name,'Медицинский кабинет');
assert.equal(JSON.parse(JSON.stringify(target)).cards.bunker.length,2);
const mixed=availableLibraryCards(packs,[orphan,{id:'blocked',type:'disaster'}]);
assert.equal(mixed.length,4);assert.ok(mixed.every(c=>c.type!=='disaster'));
assert.equal(availableLibraryCards(packs,[orphan],'health',{packId:'p1',query:'ЗДОР'}).length,1);
const destination={cards:{bunker:[],health:[]},customTypes:[]};
const custom={id:'custom_trait',name:'Свои карты'};
assert.equal(addSelectedLibraryCards(destination,[...mixed,{id:'custom',type:custom.id,name:'Свойство'}],new Set(['a','h','custom']),[{id:'bunker'},{id:'health'},custom]),3);
assert.equal(destination.cards.bunker.length,1);assert.equal(destination.cards.health.length,1);
assert.equal(destination.cards.custom_trait[0].id,'custom');assert.deepEqual(destination.customTypes,[custom]);
const source=fs.readFileSync('app.js','utf8');
const picker=source.slice(source.indexOf('function openLibraryPicker(){'),source.indexOf("\ndocument.addEventListener('click',e=>{if(e.target.closest('[data-library-picker]'))"));
assert.doesNotThrow(()=>vm.runInNewContext(picker+';openLibraryPicker()', {superadminWorkspace:false}), 'Unauthorized picker calls return before accessing data or the DOM');
const page=source.split('\n').find(line=>line.startsWith('function cardsPage()'));
const render=admin=>vm.runInNewContext(page+';cardsPage()', {query:'',cardWord:()=>'',section:'profession',cats:[{id:'profession',name:'Профессия'}],minimumFor:()=>1,pack:{cards:{profession:[]}},heading:(_a,_b,_c,actions)=>actions,esc:String,btn:label=>label,icon:()=>'',superadminWorkspace:admin,supportsTable:()=>false,cardReadinessFilter:()=>'',cardList:()=>'',nextLabel:()=>'',nextId:()=>''});
assert.ok(!render(false).includes('Выбрать из списка'));assert.ok(render(true).includes('Выбрать из списка'));
const themes=source.split('\n').filter(line=>line.startsWith('const packThemes=')||line.startsWith('const packTheme=')).join('\n');
assert.equal(vm.runInNewContext(themes+';packThemes[packTheme({theme:"other"})]'),'Другое');
console.log('Card picker: type isolation, pack/name filters, deduplication, orphan cards, metadata and source isolation passed.');
