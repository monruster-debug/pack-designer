import assert from 'node:assert/strict';
import {buildCardLibrary,filterAdminCards,changeUser,demoUsers,updateCardInPacks,mergeAdminDemoData,demoLinkedPacks,paginateAdmin} from '../admin-model.js';

const source=[{id:'pack-a',cards:{profession:[{id:'shared',name:'Полярный врач',description:'Медицина'}]}},{id:'pack-b',cards:{profession:[{id:'shared',name:'Полярный врач',description:'Медицина'},{id:'second',name:'Радист',description:'Связь'}],bunker:[{id:'room',name:'Теплица'}]}}];
const records=Array.from({length:101},(_,id)=>({id}));
assert.equal(paginateAdmin(records).rows.length,50);
assert.equal(paginateAdmin(records,2).rows[0].id,50);
assert.equal(paginateAdmin(records,2).rows.length,50);
assert.equal(paginateAdmin(records,3).rows.length,1);
assert.equal(paginateAdmin([],10).page,1);
assert.equal(paginateAdmin(records,100).page,3);
const original=structuredClone(source),cards=buildCardLibrary(source);
const demoCards=buildCardLibrary(demoLinkedPacks());
assert.deepEqual(demoCards.map(c=>c.packIds.length),[1,2,3]);
assert.ok(demoCards.every(c=>c.adminDemo));
assert.equal(cards.length,3);
assert.deepEqual(cards[0].packIds,['pack-a','pack-b'],'Shared IDs produce one library card');
assert.equal(filterAdminCards(cards,{query:'ВРАЧ',pack:'pack-b',type:'profession'}).length,1);
assert.equal(filterAdminCards(cards,{query:'МЕДИЦИНА'}).length,1);
assert.equal(filterAdminCards(cards,{query:'shared'}).length,1);
assert.equal(filterAdminCards(cards,{pack:'pack-a',type:'bunker'}).length,0);
cards[0].name='Изменено';assert.deepEqual(source,original,'Preview edits never mutate workshop packs');
const updated=updateCardInPacks(source,cards[0],'shared');
assert.equal(updated[0].cards.profession[0].name,'Изменено');
assert.equal(updated[1].cards.profession.find(c=>c.id==='shared').name,'Изменено','Edit propagates to every linked pack');
assert.equal(updated[1].cards.profession.find(c=>c.id==='second').name,'Радист');
const deleted=updateCardInPacks(updated,null,'shared');
assert.ok(deleted.every(p=>Object.values(p.cards).every(list=>list.every(c=>c.id!=='shared'))),'Delete removes every pack reference');
const moved=updateCardInPacks(source,{...cards[0],packIds:['pack-b']},'shared');
assert.equal(moved[0].cards.profession.length,0);assert.equal(moved[1].cards.profession.length,2);
assert.deepEqual(source,original,'Updates are staged without mutating the original library before saving');
const users=demoUsers();
assert.equal(users.length,30);assert.equal(new Set(users.map(u=>u.id)).size,30);
const saved={cards:[],users:[{...users[0],nickname:'Сохранённое имя',warnings:[{reason:'Сохранённое предупреждение'}]}],audit:[{id:'real-entry',description:'Настоящее локальное действие'}]};
const merged=mergeAdminDemoData(saved);
assert.equal(merged.users.length,30);assert.equal(merged.users[0].nickname,'Сохранённое имя');
assert.equal(merged.users[0].warnings.length,1);assert.equal(merged.audit[0].id,'real-entry');
assert.equal(merged.audit.filter(a=>a.demo).length,8);
assert.equal(mergeAdminDemoData(merged).audit.length,merged.audit.length,'Demo logs append once');
assert.equal(mergeAdminDemoData(merged).users.length,30,'Demo users append once');
changeUser(users,'101024','role','player');
assert.throws(()=>changeUser(users,'100042','role','player'),/последнего/);
assert.throws(()=>changeUser(users,'100042','block'),/последнего/);
changeUser(users,'100128','role','superadmin');
changeUser(users,'100042','role','player');
assert.equal(users.find(u=>u.id==='100042').role,'player');
const user=users.find(u=>u.id==='100256'),old=user.nickname;
changeUser(users,user.id,'rename');
assert.equal(user.nickname,'Игрок100256');assert.equal(user.warnings[0].previousNickname,old);
assert.match(user.warnings[0].reason,/Никнейм/);
changeUser(users,user.id,'block');assert.equal(user.blocked,true);
changeUser(users,user.id,'block');assert.equal(user.blocked,false);
assert.throws(()=>changeUser(users,'missing','block'),/не найден/);
assert.throws(()=>changeUser(users,user.id,'role','owner'),/роль/);
console.log('Admin preview: shared cards, combined filters, source isolation, last-admin protection, roles, nickname warning, permanent block/unblock passed.');
